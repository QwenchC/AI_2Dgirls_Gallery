"""Compile reviewed research into one offline data bundle and 14 text dossiers."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
def read(path):
    return json.loads((ROOT/path).read_text(encoding='utf-8-sig'))

def main():
    characters = read('research/characters-a.json') + read('research/characters-b.json')
    visuals = read('data/visual-notes.json')
    images = read('data/image-index.json')
    characters.sort(key=lambda c: list(visuals).index(c['id']))
    if len(characters) != 14 or len({c['id'] for c in characters}) != 14:
        raise ValueError('Expected exactly fourteen unique character records')
    folder = ROOT/'docs'/'characters'
    folder.mkdir(parents=True, exist_ok=True)
    bibliography = ['# 研究来源与证据范围', '', '调研截至 2026-10-30。以下链接是社区创作及设定线索，不等同于当前 42 张生成图的完整来源或授权链。部分内容仅能通过搜索索引摘要核对，限制逐项保留。', '', '每份角色资料均将社区证据、当前图片的视觉观察与本项目二创建议分开。无足够公开证据时不补写“公认人设”。网络摘录只用于说明证据，不收录完整原文或上游图片。', '', '## 索引', '']
    source_count=0
    for c in characters:
        slug=c['id'];c['visual']=visuals[slug];c['images']=images[slug]
        p=c['projectSetting'];v=c['visual']
        traits='\n'.join(f"- {x['text']} [来源：{', '.join(x['sourceIds'])}]" for x in c['communityTraits'])
        relationships=p['relationships'] if isinstance(p['relationships'],str) else '；'.join(p['relationships'])
        lines=[f"# {v['label']} · 角色资料", '', '更新时间：2026-10-30', '', '## 社区资料与证据', '', c['communitySummary'], '', traits or '暂无足够证据支持固定性格。', '', '## 本仓库图片的视觉观察', '', v['visual'], '', '以上按标准版观察；细节以实际所选体型原图为准。多视图设定板可能存在生成误差。体型不代表年龄。', '', '## 本项目二创设定（非官方、非社区共识）', '', f"- 展签：{v['subtitle']}",f"- 定位：{p['role']}",f"- 背景：{p['background']}",f"- 性格：{'、'.join(p['personality'])}",f"- 表达方式：{p['speechStyle']}",f"- 关系灵感：{relationships}",'', '### 场景建议', '', *[f'- {x}' for x in p['scenes']], '', '## 三种体型', '']
        for key,label in [('standard','标准版'),('medium','中间体型版'),('chibi','Q版')]:
            lines.append(f"- [{label}原图](../../{c['images'][key]['original']})")
        lines += ['', '## 来源', '']
        bibliography += [f"### {v['label']}", '', f"[本地角色资料](characters/{slug}.md)", '', c['communitySummary'], '']
        for s in c['sources']:
            source_count+=1
            block=[f"### [{s['id']}] {s['title']}",'',f"- 链接：[{s['title']}]({s['url']})",f"- 作者／发布者：{s['author'] or '待核实'}",f"- 发布日期：{s['date'] or '待核实'}；访问日期：{s['accessed']}",f"- 证据支持：{s['evidence']}",f"- 使用范围与限制：{s['limits']}",'']
            lines+=block
            bibliography += [f"- **[{s['id']}] [{s['title']}]({s['url']})** — {s['author']} / {s['date']}",f"  - 支持：{s['evidence']}",f"  - 限制：{s['limits']}", '']
        lines += ['## 待核实与检索记录','',*[f'- {x}' for x in c['searchNotes']], '', '## 图片来源与致谢', '', '特别感谢 Creeper-北极之光提供初始形象图。本仓库图片由项目维护者使用 GPT 参考其提供的图片生成；其图片是否进一步参考他人作品尚未考证。调研来源不等于本图授权链。侵删；为形象做出贡献的创作者可联系维护者补充名字及贡献说明。致谢与侵删不替代授权。', '']
        (folder/f'{slug}.md').write_text('\n'.join(lines),encoding='utf-8')
    bibliography += ['## 初始参考来源', '', 'Creeper-北极之光：由维护者确认提供初始形象参考图。本次尚未核验其公开主页或更上游来源，不猜测 UID，不认定为全体角色原作者。', '', '## 检索记录', '', '- [角色组 A 的检索记录](../research/research-a.md)', '- [角色组 B 的检索记录](../research/research-b.md)', '', '上游作品若有具体授权约定，仅能适用于其声明覆盖的作品；不扩展为全角色或本仓库的统一授权。', '']
    (ROOT/'docs'/'sources.md').write_text('\n'.join(bibliography),encoding='utf-8')
    bundle={'updated':'2026-10-30','characters':characters,'workflow':read('data/workflow-guide.json')}
    payload=json.dumps(bundle,ensure_ascii=False,indent=2)
    (ROOT/'data'/'gallery-data.json').write_text(payload,encoding='utf-8')
    (ROOT/'data'/'gallery-data.js').write_text('/* Generated by scripts/build_data.py; do not edit by hand. */\nwindow.AI_GALLERY = '+payload+';\n',encoding='utf-8')
    print(f'Compiled {len(characters)} dossiers and {source_count} source references.')

if __name__=='__main__':
    main()
